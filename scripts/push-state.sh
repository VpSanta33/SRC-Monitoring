#!/usr/bin/env bash
set -euo pipefail
test -s .state/state/manifest.json
test -s web/public/data/manifest.json
git -C .state config user.name 'github-actions[bot]'
git -C .state config user.email '41898282+github-actions[bot]@users.noreply.github.com'
cat > .state/README.md <<'TEXT'
# Monitoring state

Generated by the Pages workflow. This branch stores public scope baselines and change history as checksummed JSONL shards. It contains no credentials or visitor preferences.

Do not delete or rewrite this branch to redeploy the UI: the collector needs its previous baseline. Application source and deployment documentation live on `main`.
TEXT
git -C .state add -- state README.md
if ! git -C .state diff --cached --quiet; then
  git -C .state commit -m 'Update public scope monitoring state'
fi
git -C .state -c credential.helper='!gh auth git-credential' push origin HEAD:monitor-state
